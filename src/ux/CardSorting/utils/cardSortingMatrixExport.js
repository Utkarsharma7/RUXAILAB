const UNASSIGNED_KEY = '__unassigned'

export function formatMatrixValue(count, displayMode, totalParticipants) {
  if (!count) return ''
  if (displayMode === 'percentage' && totalParticipants) {
    const pct = Math.round((count / totalParticipants) * 1000) / 10
    return `${pct}%`
  }
  return String(count)
}

export function escapeLatex(text) {
  return String(text)
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([&%$#_{}])/g, '\\$1')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}')
}

/**
 * Build a LaTeX tabular for the card × category matrix.
 */
export function buildCategoryMatrixLatex({
  title,
  cardLabel,
  cardTitles,
  categoryTitles,
  unassignedLabel,
  matrix,
  displayMode,
  totalParticipants,
}) {
  const columns = [...categoryTitles, unassignedLabel]
  const colSpec = `l|${'c'.repeat(columns.length)}`
  const header = [
    escapeLatex(cardLabel),
    ...columns.map((c) => escapeLatex(c)),
  ].join(' & ')

  const rows = cardTitles.map((card) => {
    const values = [
      ...categoryTitles.map((category) =>
        formatMatrixValue(
          matrix[card]?.[category] || 0,
          displayMode,
          totalParticipants,
        ),
      ),
      formatMatrixValue(
        matrix[card]?.[UNASSIGNED_KEY] || 0,
        displayMode,
        totalParticipants,
      ),
    ].map((value) => escapeLatex(value || '—'))

    return `${escapeLatex(card)} & ${values.join(' & ')} \\\\`
  })

  return [
    `% ${title}`,
    `% Generated by RUXAILAB · ${totalParticipants} participants · ${displayMode}`,
    '\\begin{table}[ht]',
    '\\centering',
    `\\caption{${escapeLatex(title)}}`,
    `\\begin{tabular}{${colSpec}}`,
    '\\hline',
    `${header} \\\\`,
    '\\hline',
    ...rows,
    '\\hline',
    '\\end{tabular}',
    '\\end{table}',
    '',
  ].join('\n')
}

export function downloadTextFile(content, filename, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: mimeType })
  downloadBlob(blob, filename)
}

export function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  link.click()
  URL.revokeObjectURL(url)
}

function measureTextWidth(ctx, text) {
  return ctx.measureText(String(text)).width
}

function wrapHeader(ctx, text, maxWidth) {
  const words = String(text).split(/\s+/)
  const lines = []
  let current = words[0] || ''

  for (let i = 1; i < words.length; i += 1) {
    const candidate = `${current} ${words[i]}`
    if (measureTextWidth(ctx, candidate) <= maxWidth) {
      current = candidate
    } else {
      lines.push(current)
      current = words[i]
    }
  }
  if (current) lines.push(current)
  return lines.length ? lines : ['']
}

/**
 * Render the full matrix to a PNG (not just the scrolled viewport).
 */
export function exportCategoryMatrixPng({
  title,
  cardLabel,
  cardTitles,
  categoryTitles,
  unassignedLabel,
  matrix,
  displayMode,
  totalParticipants,
  filename,
}) {
  const headers = [cardLabel, ...categoryTitles, unassignedLabel]
  const rowLabelWidth = 150
  const colWidth = 64
  const rowHeight = 28
  const headerHeight = 52
  const padding = 24
  const titleHeight = 36

  const width = padding * 2 + rowLabelWidth + (headers.length - 1) * colWidth
  const height =
    padding * 2 + titleHeight + headerHeight + cardTitles.length * rowHeight

  const canvas = document.createElement('canvas')
  const scale = 2
  canvas.width = width * scale
  canvas.height = height * scale
  const ctx = canvas.getContext('2d')
  ctx.scale(scale, scale)

  ctx.fillStyle = '#ffffff'
  ctx.fillRect(0, 0, width, height)

  ctx.fillStyle = '#111827'
  ctx.font = 'bold 16px sans-serif'
  ctx.fillText(title, padding, padding + 18)

  ctx.font = '600 11px sans-serif'
  const headerY = padding + titleHeight

  headers.forEach((header, index) => {
    const x =
      index === 0
        ? padding
        : padding + rowLabelWidth + (index - 1) * colWidth
    const cellWidth = index === 0 ? rowLabelWidth : colWidth
    ctx.fillStyle = '#f3f4f6'
    ctx.fillRect(x, headerY, cellWidth, headerHeight)
    ctx.strokeStyle = '#e5e7eb'
    ctx.strokeRect(x, headerY, cellWidth, headerHeight)

    ctx.fillStyle = '#374151'
    const lines = wrapHeader(ctx, header, cellWidth - 8)
    lines.slice(0, 3).forEach((line, lineIndex) => {
      ctx.fillText(line, x + 4, headerY + 16 + lineIndex * 12)
    })
  })

  cardTitles.forEach((card, rowIndex) => {
    const y = headerY + headerHeight + rowIndex * rowHeight

    ctx.fillStyle = '#ffffff'
    ctx.fillRect(padding, y, rowLabelWidth, rowHeight)
    ctx.strokeStyle = '#e5e7eb'
    ctx.strokeRect(padding, y, rowLabelWidth, rowHeight)
    ctx.fillStyle = '#111827'
    ctx.font = '600 11px sans-serif'
    const label =
      card.length > 22 ? `${card.slice(0, 21)}…` : card
    ctx.fillText(label, padding + 6, y + 18)

    const values = [
      ...categoryTitles.map((category) => matrix[card]?.[category] || 0),
      matrix[card]?.[UNASSIGNED_KEY] || 0,
    ]

    values.forEach((count, colIndex) => {
      const x = padding + rowLabelWidth + colIndex * colWidth
      const intensity =
        count && totalParticipants ? count / totalParticipants : 0
      const isUnassigned = colIndex === values.length - 1

      if (count && !isUnassigned) {
        ctx.fillStyle = `rgba(63, 81, 181, ${0.15 + intensity * 0.6})`
      } else {
        ctx.fillStyle = '#ffffff'
      }
      ctx.fillRect(x, y, colWidth, rowHeight)
      ctx.strokeStyle = '#e5e7eb'
      ctx.strokeRect(x, y, colWidth, rowHeight)

      const text = formatMatrixValue(count, displayMode, totalParticipants)
      if (!text) return
      ctx.fillStyle =
        !isUnassigned && intensity > 0.6 ? '#ffffff' : '#4b5563'
      ctx.font = '600 11px sans-serif'
      const textWidth = measureTextWidth(ctx, text)
      ctx.fillText(text, x + (colWidth - textWidth) / 2, y + 18)
    })
  })

  return new Promise((resolve, reject) => {
    canvas.toBlob((blob) => {
      if (!blob) {
        reject(new Error('Failed to create PNG'))
        return
      }
      downloadBlob(blob, filename)
      resolve()
    }, 'image/png')
  })
}
